#!/usr/bin/env python3
"""Render the sourced timeline; run --check to detect stale generated content."""
import argparse
import json
from collections import Counter
from html import escape as e
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def render(data):
    items = data['items']
    assert len(items) == 47 and len({i['id'] for i in items}) == 47
    assert Counter(i['decade'] for i in items) == dict(zip(['1970s','1980s','1990s','2000s','2010s','2020s'], [6,6,9,10,9,7]))
    assert not set(data['excluded']) & {i['label'] for i in items}
    out = ['#+TITLE: Impact', '#+HTML_CONTENT_CLASS: impact-page', "#+DESCRIPTION: A historical portfolio of the SRI Formal Methods Program's impact.", '', '# Generated by scripts/render_impact.py from data/impact-history.json.', '#+begin_export html', '<figure class="fm-history" aria-labelledby="fm-history-title" aria-describedby="fm-history-caption">', '<header class="fm-history-header"><p class="fm-history-kicker">SRI Formal Methods Program</p><h2 id="fm-history-title">Six decades of research and contributions</h2><p>Explore a contribution for its description, key references, and selected SRI contributors. Hover, focus, or select an item.</p></header>', '<div class="fm-history-map">']
    for n, decade in enumerate(dict.fromkeys(i['decade'] for i in items), 1):
        out += [f'<section class="fm-history-era era-{n}" aria-labelledby="history-{decade}"><h3 id="history-{decade}">{decade}</h3><div class="fm-history-cluster"><ul>']
        for i in (i for i in items if i['decade'] == decade):
            assert i['sources'] and (i['sri_contributors'] or i['gap'])
            ident=e(i['id']);label=e(i['label'])
            out += [f'<li><details class="history-item" id="{ident}"><summary id="trigger-{ident}" aria-controls="panel-{ident}">{label}</summary><div class="history-panel" id="panel-{ident}" role="region" aria-labelledby="trigger-{ident}">', f'<p class="history-panel-title">{label} <span>· {decade}</span></p>']
            if i['description']: out += [f'<p>{e(i["description"])}</p>']
            if i['sri_contributors']: out += [f'<p><strong>Selected SRI contributors:</strong> {e(", ".join(i["sri_contributors"]))}.</p>']
            if i['collaborators']: out += [f'<p><strong>Collaborators / other affiliations:</strong> {e(i["collaborators"])}</p>']
            if i['public_note']: out += [f'<p>{e(i["public_note"])}</p>']
            out += ['<p class="history-source-heading">Papers &amp; project resources</p><ul class="history-sources">']
            for sid in i['sources']:
                s=data['sources'][sid];assert s['evidence'] and s['url'].startswith('https://')
                out += [f'<li><a href="{e(s["url"],quote=True)}">{e(s["title"])}</a></li>']
            out += ['</ul></div></details></li>']
        out += ['</ul></div></section>']
    out += ['</div>', '<figcaption id="fm-history-caption">One program, many connected contributions. The axis shows chronology, not dependencies. Decade groupings and descriptions follow the <a href="/images/sri_fm_history.jpg">original historical figure</a>.</figcaption>', '</figure>', '<script src="/js/impact-history.js" defer></script>', '#+end_export', '', 'Here are some of the early', '[[https://www.csl.sri.com/users/rushby/history/][accomplishments]]', 'of the Computer Science Labs (CSL) and several sibling labs.', '']
    return '\n'.join(out)

if __name__ == '__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    result=render(json.loads((ROOT/'data/impact-history.json').read_text()))
    target=ROOT/'content/impact.org'
    if args.check:
        assert target.read_text() == result, 'Run python3 scripts/render_impact.py'
        print('Impact: 47 unique items, six eras, sourced attribution or explicit gaps; generated content current.')
    else: target.write_text(result)
